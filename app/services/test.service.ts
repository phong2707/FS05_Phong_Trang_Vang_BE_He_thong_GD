export async function getLeaderboard(testId: string) {
  return prisma.submission.findMany({
    where: { testId, status: "GRADED" },
    orderBy: [{ score: "desc" }, { submittedAt: "asc" }],
    take: 50,
    include: {
      student: {
        select: {
          id: true,
          email: true,
        },
      },
    },
  });
}

